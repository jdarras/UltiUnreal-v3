import { TASK_STATUS_FLOW } from "../../helpers";
import { useTasksPreferences } from "../useTasksPreferences";
import { useTasksCatalogOptions } from "../useTasksCatalogOptions";
import { useTasksListController } from "../useTasksListController";
import { useTasksFormUiState } from "../useTasksFormUiState";

export function useTasksCardListData({
  t,
  tasks = [],
  renders = [],
  projectOptions = [],
  resourceOptions = [],
  renderTemplates = [],
  renderForms = [],
  renderWorkers = [],
  onFormModeChange = null,
} = {}) {
  const {
    title,
    setTitle,
    description,
    setDescription,
    selectedResourceRefs,
    setSelectedResourceRefs,
    showCreateForm,
    setShowCreateForm,
    editingTaskId,
    setEditingTaskId,
    formError,
    setFormError,
    editAutosaveStateRef,
    isEditingTask,
  } = useTasksFormUiState({
    onFormModeChange,
  });

  const {
    viewMode,
    setViewMode,
    listSortKey,
    setListSortKey,
    listSortDir,
    setListSortDir,
    searchQuery,
    setSearchQuery,
    searchExpanded,
    setSearchExpanded,
    favoriteOnly,
    setFavoriteOnly,
    taskFavorites,
    setTaskFavorites,
    listStatusFilter,
    setListStatusFilter,
    listRenderWorkerFilter,
    setListRenderWorkerFilter,
    listProjectFilter,
    setListProjectFilter,
    listFormFilter,
    setListFormFilter,
    listRenderModeFilter,
    setListRenderModeFilter,
    listResourceFilter,
    setListResourceFilter,
  } = useTasksPreferences({ taskStatusFlow: TASK_STATUS_FLOW });

  const {
    normalizedRenderWorkers,
    availableRenderWorkers,
    normalizedProjectOptions,
    normalizedRenderTemplateOptions,
    normalizedResourceOptions,
  } = useTasksCatalogOptions({
    renderWorkers,
    projectOptions,
    renderTemplates,
    resourceOptions,
    selectedResourceRefs,
    setSelectedResourceRefs,
    listResourceFilter,
    setListResourceFilter,
  });

  const {
    taskRenderWorkerFilterOptions,
    taskFormFilterOptions,
    taskRenderModeFilterOptions,
    displayedTasks,
    hasActiveListFilters,
    isTaskFavorite,
    toggleTaskFavorite,
    taskVisualStatus,
    taskExpectedRenderName,
    taskRenderWorkerLabel,
    taskLaunchModeLabel,
    taskRenderFormLabel,
    taskRenderModeName,
    setListSortFromSelect,
    toggleListSort,
  } = useTasksListController({
    t,
    tasks,
    renders,
    renderForms,
    normalizedProjectOptions,
    normalizedResourceOptions,
    normalizedRenderWorkers,
    favoriteOnly,
    taskFavorites,
    setTaskFavorites,
    searchQuery,
    listStatusFilter,
    listRenderWorkerFilter,
    setListRenderWorkerFilter,
    listProjectFilter,
    setListProjectFilter,
    listFormFilter,
    setListFormFilter,
    listRenderModeFilter,
    setListRenderModeFilter,
    listSortKey,
    setListSortKey,
    listSortDir,
    setListSortDir,
  });

  return {
    title,
    setTitle,
    description,
    setDescription,
    selectedResourceRefs,
    setSelectedResourceRefs,
    showCreateForm,
    setShowCreateForm,
    editingTaskId,
    setEditingTaskId,
    formError,
    setFormError,
    editAutosaveStateRef,
    isEditingTask,
    viewMode,
    setViewMode,
    listSortKey,
    setListSortKey,
    listSortDir,
    setListSortDir,
    searchQuery,
    setSearchQuery,
    searchExpanded,
    setSearchExpanded,
    favoriteOnly,
    setFavoriteOnly,
    listStatusFilter,
    setListStatusFilter,
    listRenderWorkerFilter,
    setListRenderWorkerFilter,
    listProjectFilter,
    setListProjectFilter,
    listFormFilter,
    setListFormFilter,
    listRenderModeFilter,
    setListRenderModeFilter,
    setListResourceFilter,
    normalizedProjectOptions,
    normalizedRenderTemplateOptions,
    availableRenderWorkers,
    taskRenderWorkerFilterOptions,
    taskFormFilterOptions,
    taskRenderModeFilterOptions,
    displayedTasks,
    hasActiveListFilters,
    isTaskFavorite,
    toggleTaskFavorite,
    taskVisualStatus,
    taskExpectedRenderName,
    taskRenderWorkerLabel,
    taskLaunchModeLabel,
    taskRenderFormLabel,
    taskRenderModeName,
    setListSortFromSelect,
    toggleListSort,
  };
}

export default useTasksCardListData;
