import { useRendersPreferences } from "./useRendersPreferences";
import { useRendersCardControllers } from "./useRendersCardControllers";
import { buildRendersCardDataOutput } from "./buildRendersCardDataOutput";

export function useRendersCardData({
  t,
  user = null,
  renders = [],
  tasks = [],
  renderWorkers = [],
  onTransitionRender = null,
  onLoadRenderTransitions = null,
  onCreateRender = null,
  onDispatchRenders = null,
} = {}) {
  const preferences = useRendersPreferences();
  const {
    searchQuery,
    setSearchQuery,
    reviewFilter,
    setReviewFilter,
    projectFilter,
    setProjectFilter,
    searchExpanded,
    setSearchExpanded,
    favoriteOnly,
    setFavoriteOnly,
    renderFavorites,
    setRenderFavorites,
    viewMode,
    setViewMode,
    listSortKey,
    setListSortKey,
    listSortDir,
    setListSortDir,
    queueSortKey,
    setQueueSortKey,
    queueSortDir,
    setQueueSortDir,
  } = preferences;

  const { review, list, detail, queue, toolbar } = useRendersCardControllers({
    t,
    user,
    renders,
    tasks,
    renderWorkers,
    onTransitionRender,
    onLoadRenderTransitions,
    onCreateRender,
    onDispatchRenders,
    preferences: {
      searchQuery,
      setSearchQuery,
      reviewFilter,
      setReviewFilter,
      projectFilter,
      setProjectFilter,
      searchExpanded,
      setSearchExpanded,
      favoriteOnly,
      setFavoriteOnly,
      renderFavorites,
      setRenderFavorites,
      listSortKey,
      setListSortKey,
      listSortDir,
      setListSortDir,
      queueSortKey,
      setQueueSortKey,
      queueSortDir,
      setQueueSortDir,
    },
  });

  const {
    canReviewRenders,
    busyRenderId,
    applyReviewStatus,
  } = review;

  const {
    projectFilterOptions,
    hasActiveFilters,
    sortedDisplayedRenders,
    isRenderFavorite,
    toggleRenderFavorite,
    listSortIndicator,
    toggleListSort,
    setListSortFromSelect,
  } = list;

  const {
    buildRenderThumbCandidates,
    openRenderOutputExternally,
    openRenderDetail,
    closeRenderDetail,
    advancePreviewCandidate,
    detailRender,
    detailPreviewKind,
    detailPreviewSource,
    detailPreviewError,
    detailPreviewCandidatesCount,
    detailTransitions,
    detailTransitionsLoading,
    detailTransitionsError,
  } = detail;

  const {
    busyScheduledTaskId,
    queueBatchBusyMode,
    queueBatchFeedback,
    queueBatchError,
    renderQueueTasks,
    filteredRenderQueueTasks,
    sortedRenderQueueTasks,
    selectedQueueEntrySet,
    launchableQueueTaskIdSet,
    selectedLaunchableQueueEntries,
    queueStateSummary,
    queueSortIndicator,
    canLaunchRenders,
    queueEntryWorkerLabel,
    getQueueEntryLaunchMeta,
    queueTaskPriorityLabel,
    toggleSelectAllQueueEntries,
    launchQueueBatch,
    toggleQueueSort,
    toggleQueueTaskSelection,
    launchScheduledTaskRender,
  } = queue;

  const {
    clearFilters,
    openAdvancedSearch,
    closeAdvancedSearch,
    toggleFavoriteOnly,
  } = toolbar;

  return buildRendersCardDataOutput({
    preferences: {
      searchQuery,
      setSearchQuery,
      reviewFilter,
      setReviewFilter,
      projectFilter,
      setProjectFilter,
      searchExpanded,
      favoriteOnly,
      viewMode,
      setViewMode,
      listSortKey,
      listSortDir,
    },
    review: {
      canReviewRenders,
      busyRenderId,
      applyReviewStatus,
    },
    list: {
      projectFilterOptions,
      hasActiveFilters,
      sortedDisplayedRenders,
      isRenderFavorite,
      toggleRenderFavorite,
      listSortIndicator,
      toggleListSort,
      setListSortFromSelect,
    },
    detail: {
      buildRenderThumbCandidates,
      openRenderOutputExternally,
      openRenderDetail,
      closeRenderDetail,
      advancePreviewCandidate,
      detailRender,
      detailPreviewKind,
      detailPreviewSource,
      detailPreviewError,
      detailPreviewCandidatesCount,
      detailTransitions,
      detailTransitionsLoading,
      detailTransitionsError,
    },
    queue: {
      busyScheduledTaskId,
      queueBatchBusyMode,
      queueBatchFeedback,
      queueBatchError,
      renderQueueTasks,
      filteredRenderQueueTasks,
      sortedRenderQueueTasks,
      selectedQueueEntrySet,
      launchableQueueTaskIdSet,
      selectedLaunchableQueueEntries,
      queueStateSummary,
      queueSortIndicator,
      canLaunchRenders,
      queueEntryWorkerLabel,
      getQueueEntryLaunchMeta,
      queueTaskPriorityLabel,
      toggleSelectAllQueueEntries,
      launchQueueBatch,
      toggleQueueSort,
      toggleQueueTaskSelection,
      launchScheduledTaskRender,
    },
    toolbar: {
      clearFilters,
      openAdvancedSearch,
      closeAdvancedSearch,
      toggleFavoriteOnly,
    },
  });
}

export default useRendersCardData;
